/* ---------- 1. TẠO BẢNG (chỉ khi chưa tồn tại) ---------- */
IF OBJECT_ID(N'dbo.ChucNang') IS NULL CREATE TABLE dbo.ChucNang(
    MaCN VARCHAR(30) NOT NULL PRIMARY KEY, TenCN NVARCHAR(100) NOT NULL);
IF OBJECT_ID(N'dbo.NhomQuyen') IS NULL CREATE TABLE dbo.NhomQuyen(
    MaNhom VARCHAR(20) NOT NULL PRIMARY KEY, TenNhom NVARCHAR(100) NOT NULL);
IF OBJECT_ID(N'dbo.PhanQuyen') IS NULL CREATE TABLE dbo.PhanQuyen(
    MaNhom VARCHAR(20) NOT NULL REFERENCES dbo.NhomQuyen(MaNhom),
    MaCN VARCHAR(30) NOT NULL REFERENCES dbo.ChucNang(MaCN),
    PRIMARY KEY(MaNhom, MaCN));
IF OBJECT_ID(N'dbo.Khoa') IS NULL CREATE TABLE dbo.Khoa(
    MaKhoa VARCHAR(10) NOT NULL PRIMARY KEY, TenKhoa NVARCHAR(100) NOT NULL);
IF OBJECT_ID(N'dbo.Nganh') IS NULL CREATE TABLE dbo.Nganh(
    MaNganh VARCHAR(10) NOT NULL PRIMARY KEY, TenNganh NVARCHAR(100) NOT NULL,
    MaKhoa VARCHAR(10) NOT NULL REFERENCES dbo.Khoa(MaKhoa));
IF OBJECT_ID(N'dbo.LopSinhHoat') IS NULL CREATE TABLE dbo.LopSinhHoat(
    MaLop VARCHAR(15) NOT NULL PRIMARY KEY, TenLop NVARCHAR(100) NOT NULL,
    MaNganh VARCHAR(10) NOT NULL REFERENCES dbo.Nganh(MaNganh), NienKhoa NVARCHAR(20) NULL);
IF OBJECT_ID(N'dbo.SinhVien') IS NULL CREATE TABLE dbo.SinhVien(
    MaSV VARCHAR(15) NOT NULL PRIMARY KEY, HoTen NVARCHAR(100) NOT NULL, NgaySinh DATE NOT NULL,
    GioiTinh NVARCHAR(3) NOT NULL, Email VARCHAR(100) NULL, SDT VARCHAR(15) NULL, DiaChi NVARCHAR(200) NULL,
    MaLop VARCHAR(15) NOT NULL REFERENCES dbo.LopSinhHoat(MaLop),
    AnhDaiDien VARBINARY(MAX) NULL, TrangThai BIT NOT NULL DEFAULT 1);
IF OBJECT_ID(N'dbo.GiangVien') IS NULL CREATE TABLE dbo.GiangVien(
    MaGV VARCHAR(15) NOT NULL PRIMARY KEY, HoTen NVARCHAR(100) NOT NULL, Email VARCHAR(100) NULL,
    SDT VARCHAR(15) NULL, MaKhoa VARCHAR(10) NOT NULL REFERENCES dbo.Khoa(MaKhoa));
IF OBJECT_ID(N'dbo.MonHoc') IS NULL CREATE TABLE dbo.MonHoc(
    MaMon VARCHAR(15) NOT NULL PRIMARY KEY, TenMon NVARCHAR(150) NOT NULL, SoTinChi TINYINT NOT NULL,
    MaKhoa VARCHAR(10) NOT NULL REFERENCES dbo.Khoa(MaKhoa));
IF OBJECT_ID(N'dbo.MonTienQuyet') IS NULL CREATE TABLE dbo.MonTienQuyet(
    MaMon VARCHAR(15) NOT NULL REFERENCES dbo.MonHoc(MaMon),
    MaMonTienQuyet VARCHAR(15) NOT NULL REFERENCES dbo.MonHoc(MaMon),
    PRIMARY KEY(MaMon, MaMonTienQuyet));
IF OBJECT_ID(N'dbo.HocKy') IS NULL CREATE TABLE dbo.HocKy(
    MaHK VARCHAR(15) NOT NULL PRIMARY KEY, TenHK NVARCHAR(50) NOT NULL, NamHoc VARCHAR(15) NOT NULL,
    TuNgay DATE NOT NULL, DenNgay DATE NOT NULL, DonGiaTinChi DECIMAL(18,0) NOT NULL);
IF OBJECT_ID(N'dbo.LopHocPhan') IS NULL CREATE TABLE dbo.LopHocPhan(
    MaLHP VARCHAR(20) NOT NULL PRIMARY KEY,
    MaMon VARCHAR(15) NOT NULL REFERENCES dbo.MonHoc(MaMon),
    MaGV VARCHAR(15) NOT NULL REFERENCES dbo.GiangVien(MaGV),
    MaHK VARCHAR(15) NOT NULL REFERENCES dbo.HocKy(MaHK),
    SiSoToiDa SMALLINT NOT NULL, Thu TINYINT NOT NULL, TietBatDau TINYINT NOT NULL, SoTiet TINYINT NOT NULL,
    Phong NVARCHAR(20) NULL);
IF OBJECT_ID(N'dbo.NguoiDung') IS NULL CREATE TABLE dbo.NguoiDung(
    MaND INT IDENTITY(1,1) NOT NULL PRIMARY KEY, TenDangNhap VARCHAR(50) NOT NULL UNIQUE,
    MatKhauHash VARCHAR(100) NOT NULL, Salt VARCHAR(50) NOT NULL,
    MaNhom VARCHAR(20) NOT NULL REFERENCES dbo.NhomQuyen(MaNhom),
    MaSV VARCHAR(15) NULL REFERENCES dbo.SinhVien(MaSV),
    MaGV VARCHAR(15) NULL REFERENCES dbo.GiangVien(MaGV),
    TrangThai BIT NOT NULL DEFAULT 1);
IF OBJECT_ID(N'dbo.DangKyHocPhan') IS NULL CREATE TABLE dbo.DangKyHocPhan(
    MaDK INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaSV VARCHAR(15) NOT NULL REFERENCES dbo.SinhVien(MaSV),
    MaLHP VARCHAR(20) NOT NULL REFERENCES dbo.LopHocPhan(MaLHP),
    NgayDK DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT UQ_DangKy UNIQUE(MaSV, MaLHP));
IF OBJECT_ID(N'dbo.Diem') IS NULL CREATE TABLE dbo.Diem(
    MaDK INT NOT NULL PRIMARY KEY REFERENCES dbo.DangKyHocPhan(MaDK),
    DiemCC DECIMAL(3,1) NULL, DiemGK DECIMAL(3,1) NULL, DiemCK DECIMAL(3,1) NULL,
    DiemTongKet DECIMAL(3,1) NULL, DiemChu NVARCHAR(2) NULL, Diem4 DECIMAL(2,1) NULL);
IF OBJECT_ID(N'dbo.NhatKyDiem') IS NULL CREATE TABLE dbo.NhatKyDiem(
    MaNK INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaDK INT NOT NULL REFERENCES dbo.DangKyHocPhan(MaDK),
    DiemCu NVARCHAR(100) NULL, DiemMoi NVARCHAR(100) NULL,
    NguoiSua INT NOT NULL REFERENCES dbo.NguoiDung(MaND), NgaySua DATETIME NOT NULL DEFAULT GETDATE());
IF OBJECT_ID(N'dbo.PhieuThu') IS NULL CREATE TABLE dbo.PhieuThu(
    MaPhieu INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaSV VARCHAR(15) NOT NULL REFERENCES dbo.SinhVien(MaSV),
    MaHK VARCHAR(15) NOT NULL REFERENCES dbo.HocKy(MaHK),
    TongTinChi SMALLINT NOT NULL, TongTien DECIMAL(18,0) NOT NULL, GiamGia DECIMAL(18,0) NOT NULL DEFAULT 0,
    PhaiThu DECIMAL(18,0) NOT NULL, DaThu DECIMAL(18,0) NOT NULL, NgayLap DATETIME NOT NULL DEFAULT GETDATE(),
    NguoiLap INT NOT NULL REFERENCES dbo.NguoiDung(MaND), GhiChu NVARCHAR(200) NULL, DaHuy BIT NOT NULL DEFAULT 0);
GO

